def _fmt_price(value):
    return f'{value:,}'.replace(',', ' ')


def page_meta(url_name, site=None, min_price=None, room=None):
    """Собирает теги страницы. Для карточки номера — свои теги из данных номера."""
    year = timezone.localdate().year
    price = f' от {_fmt_price(min_price)} сом/сутки' if min_price else ''
    phone = getattr(site, 'phone', '') or ''

    if room is not None:
        room_price = f' от {_fmt_price(room.min_price)} сом/сутки' if room.min_price else ''
        kind = 'юрта' if room.kind == 'yurt' else 'номер'
        # «Юрта на 4 гостя» уже содержит тип, а у номеров добавляем: «Номер «Люкс»»
        name = room.name if room.kind == 'yurt' else f'Номер «{room.name}»'
        return {
            'title': f'{name} в Суусамыре{room_price} — {BRAND}',
            'description': f'{room.short_description} До {room.capacity} гостей, {room.beds}. '
                           f'Цена{room_price or ""} включает трёхразовое питание и кумыс 5 раз в день.',
            'keywords': ', '.join([f'{room.name} Суусамыр', f'{kind} в Суусамыре', *BASE_KEYWORDS]),
        }

    data = PAGES.get(url_name, PAGES['home'])
    fields = {'year': year, 'price': price, 'price_title': price.replace(' от', ': от'), 'phone': phone}
    return {
        'title': data['title'].format(**fields),
        'description': data['description'].format(**fields),
        'keywords': ', '.join([*data['keywords'], *BASE_KEYWORDS]),
    }
